FIRST, LAST = 0x20, 0x7E


def columns(rows):
    """ASCII art -> GLYPH_W bytes, bit 0 = top row."""
    out = []
    for col in range(GLYPH_W):
        bits = 0
        for row in range(GLYPH_H):
            if rows[row][col] == '#':
                bits |= 1 << row
        out.append(bits)
    return out


def check():
    missing = [c for c in range(FIRST, LAST + 1) if chr(c) not in GLYPHS]
    if missing:
        raise SystemExit("missing glyphs: " + " ".join(hex(c) for c in missing))
    for ch, rows in GLYPHS.items():
        if len(rows) != GLYPH_H or any(len(r) != GLYPH_W for r in rows):
            raise SystemExit(f"glyph {ch!r} is not {GLYPH_W}x{GLYPH_H}")


def preview():
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        print(f"--- {ch!r} 0x{code:02X}")
        for row in range(GLYPH_H):
            line = "".join(
                "#" if columns(GLYPHS[ch])[c] & (1 << row) else "."
                for c in range(GLYPH_W)
            )
            print("  " + line.replace("#", "█").replace(".", " "))


def emit(path):
    body = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        cols = ", ".join(f"0x{b:02X}" for b in columns(GLYPHS[ch]))
        label = "backslash" if ch == '\\' else ch
        body.append(f"    {{{cols}}},  /* 0x{code:02X} {label} */")
    text = f"""/* Generated by scripts/genfont.py -- edit the glyph table there, not here.
 *
 * {GLYPH_W}x{GLYPH_H} font, printable ASCII 0x{FIRST:02X}-0x{LAST:02X}.
 * One byte per column, bit 0 = top row, matching SSD1306 page order.
 */
#pragma once

#include <stdint.h>

#define FONT5X7_W     {GLYPH_W}
#define FONT5X7_H     {GLYPH_H}
#define FONT5X7_FIRST 0x{FIRST:02X}
#define FONT5X7_LAST  0x{LAST:02X}

static const uint8_t font5x7[FONT5X7_LAST - FONT5X7_FIRST + 1][FONT5X7_W] = {{
{chr(10).join(body)}
}};
"""
    path.write_text(text)
    print(f"wrote {path} ({LAST - FIRST + 1} glyphs)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
